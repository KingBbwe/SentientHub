// Generates sentient-economic-backend/tests/RulesParity.mo from hex-die/engine/hexdie.js: the same inputs through the JS engine
// and through Rules.mo must give the same outcome. usage: HEXDIE=../hex-die node gen-rules-parity.js
const fs = require('fs'), path = require('path');
const H = require(path.resolve(process.env.HEXDIE || path.join(__dirname, '../../../hex-die'), 'engine/hexdie.js'));
let seed = 1127; const rnd = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);
const ri = (a, b) => a + Math.floor(rnd() * (b - a + 1)), pick = a => a[Math.floor(rnd() * a.length)];
const q = JSON.stringify;
const mode = m => '#' + m, tier = t => '#' + t;
const optN = n => n == null ? 'null' : '?' + n;
const inp = i => `{ cast = ${i.cast}; roll = ${i.roll}; die = ${i.die}; mod = ${i.mod}; dc = ${i.dc}; modeDc = ${optN(i.modeDc)}; stepDown = ${!!i.stepDown}; pullRoll = ${i.pullRoll}; resistPull = false }`;
const view = r => `{ pass = ${r.pass}; tier = ${tier(r.tier)}; mode = ${mode(r.mode)}; pulled = ${r.pulled}; twilight = ${r.twilight}; bolted = ${r.bolted}; castAdj = ${r.castAdj}; die = ${r.die}; joinKey = ${q(r.joinKey)}; revealedLine = ${optN(r.revealedLine)} }`;
const call = f => { try { return { ok: f() }; } catch (e) { return { err: String(e.message) }; } };
const exp = c => c.err != null ? `#err ${q(c.err)}` : `#ok ${view(c.ok)}`;

function randInput() {
  const die = pick([6, 8, 12, 20]), stepDown = rnd() < 0.3, eff = stepDown ? H.CONFIG.stepDown[die][0] : die;
  const dc = ri(1, 64), shifted = rnd() < 0.25 ? Math.max(1, Math.min(64, dc + ri(-4, 4))) : null;
  return { cast: ri(1, 64), roll: rnd() < 0.05 ? eff + 1 : ri(1, eff), die, mod: ri(-6, 6), dc: shifted == null ? dc : shifted, modeDc: shifted == null ? undefined : dc, stepDown, pullRoll: ri(1, 6) };
}
const checks = [];
for (let n = 0; n < 1500; n++) checks.push(randInput());
for (let dc = 1; dc <= 64; dc++) for (let pr = 1; pr <= 6; pr++) checks.push({ cast: 40, roll: 3, die: 6, mod: 0, dc, stepDown: false, pullRoll: pr });
for (const die of [6, 8, 12, 20]) for (const sd of [false, true]) for (let roll = 1; roll <= die; roll++) for (const dc of [5, 20, 40, 60]) checks.push({ cast: 33, roll, die, mod: 1, dc, stepDown: sd, pullRoll: 6 });
checks.push({ cast: 10, roll: 3, die: 7, mod: 0, dc: 10, stepDown: false, pullRoll: 6 }, { cast: 10, roll: 3, die: 6, mod: 0, dc: 0, stepDown: false, pullRoll: 6 }, { cast: 10, roll: 3, die: 6, mod: 0, dc: 65, stepDown: false, pullRoll: 6 });

const reveals = [], mitig = [], adj = [], keeps = [];
for (let n = 0; n < 500; n++) {
  const i = randInput(); if (i.roll > (i.stepDown ? H.CONFIG.stepDown[i.die][0] : i.die)) i.roll = 1;
  const r = H.resolveCheck(i); const line = ri(1, 7);
  reveals.push({ i, line, e: call(() => { const v = H.revealLine(r, line); return Object.assign({}, v.result, { _applied: v.applied }); }) });
  const fate = { fp: ri(0, 4), spent: ri(0, 5), sceneMitigation: ri(0, 3) }, points = ri(0, 3);
  mitig.push({ i, fate, points, e: call(() => H.mitigateDisaster(r, fate, points)) });
}
for (let n = 0; n < 800; n++) adj.push({ base: ri(1, 64), mode: pick(['over', 'under']), counts: [1, 2, 3, 4, 5, 6].map(() => ri(0, 14)) });
for (const m of ['over', 'under']) for (const a of [null, 'adv', 'dis']) for (let x = 1; x <= 6; x++) for (let y = 1; y <= 6; y++) keeps.push({ dice: a ? [x, y] : [x], mode: m, a });

let o = `// GENERATED by tools/mo-check/gen-rules-parity.js from hex-die/engine/hexdie.js. Do not hand-edit.
import Rules "../src/Rules";
import Debug "mo:base/Debug";
import Result "mo:base/Result";

type View = { pass : Bool; tier : Rules.Tier; mode : Rules.Mode; pulled : Bool; twilight : Bool; bolted : Bool; castAdj : Nat; die : Nat; joinKey : Text; revealedLine : ?Nat };
func view(r : Rules.CheckResult) : View { { pass = r.pass; tier = r.tier; mode = r.mode; pulled = r.pulled; twilight = r.twilight; bolted = r.bolted; castAdj = r.castAdj; die = r.die; joinKey = r.joinKey; revealedLine = r.revealedLine } };
func same(a : Result.Result<View, Text>, b : Result.Result<View, Text>) : Bool { a == b };
func input(c : { cast : Nat; roll : Nat; die : Nat; mod : Int; dc : Nat; modeDc : ?Nat; stepDown : Bool; pullRoll : Nat; resistPull : Bool }) : Rules.Input { c };
var failures = 0;
func fail(kind : Text, i : Nat, why : Text) { failures += 1; if (failures <= 12) { Debug.print("MISMATCH " # kind # " #" # debug_show i # ": " # why) } };

let checks : [(Rules.Input, Result.Result<View, Text>)] = [
${checks.map(i => `  (${inp(Object.assign({ modeDc: i.modeDc }, i))}, ${exp(call(() => H.resolveCheck(i)))})`).join(',\n')}
];
for (i in checks.keys()) {
  let (inp, e) = checks[i];
  let got = switch (Rules.resolveCheck(inp)) { case (#ok r) #ok(view(r)); case (#err m) #err m };
  if (not same(got, e)) { fail("check", i, debug_show got # " vs expected " # debug_show e) };
};

// revealLine: (input, line, expected: #err | #ok (applied, view))
let reveals : [(Rules.Input, Nat, Result.Result<(Bool, View), Text>)] = [
${reveals.map(c => `  (${inp(Object.assign({ modeDc: c.i.modeDc }, c.i))}, ${c.line}, ${c.e.err != null ? '#err ' + q(c.e.err) : `#ok (${c.e.ok._applied}, ${view(c.e.ok)})`})`).join(',\n')}
];
for (i in reveals.keys()) {
  let (inp, line, e) = reveals[i];
  switch (Rules.resolveCheck(inp)) {
    case (#err m) { fail("reveal-base", i, m) };
    case (#ok r) {
      let got = switch (Rules.revealLine(r, line)) { case (#ok(r2, applied)) #ok(applied, view(r2)); case (#err m) #err m };
      if (got != e) { fail("reveal", i, debug_show got # " vs expected " # debug_show e) };
    };
  };
};

// mitigateDisaster: (input, fate, points, expected: #ok (used, fate, view))
let mitig : [(Rules.Input, Rules.Fate, Nat, Result.Result<(Nat, Rules.Fate, View), Text>)] = [
${mitig.map(c => `  (${inp(Object.assign({ modeDc: c.i.modeDc }, c.i))}, { fp = ${c.fate.fp}; spent = ${c.fate.spent}; sceneMitigation = ${c.fate.sceneMitigation} }, ${c.points}, ${c.e.err != null ? '#err ' + q(c.e.err) : `#ok (${c.e.ok.used}, { fp = ${c.e.ok.fate.fp}; spent = ${c.e.ok.fate.spent}; sceneMitigation = ${c.e.ok.fate.sceneMitigation} }, ${view(c.e.ok.result)})`})`).join(',\n')}
];
for (i in mitig.keys()) {
  let (inp, fate, pts, e) = mitig[i];
  switch (Rules.resolveCheck(inp)) {
    case (#err m) { fail("mitigate-base", i, m) };
    case (#ok r) {
      let got = switch (Rules.mitigateDisaster(r, fate, pts)) { case (#ok(r2, f2, used)) #ok(used, f2, view(r2)); case (#err m) #err m };
      if (got != e) { fail("mitigate", i, debug_show got # " vs expected " # debug_show e) };
    };
  };
};

let adjusts : [(Nat, Rules.Mode, [Nat], Nat, Nat)] = [
${adj.map(c => { const r = H.adjustDC(c.base, c.mode, { 1: c.counts[0], 2: c.counts[1], 3: c.counts[2], 4: c.counts[3], 5: c.counts[4], 6: c.counts[5] }); return `  (${c.base}, ${mode(c.mode)}, [${c.counts.join(', ')}], ${r.dc}, ${r.shift})`; }).join(',\n')}
];
for (i in adjusts.keys()) {
  let (b, m, counts, dc, shift) = adjusts[i];
  let got = Rules.adjustDC(b, m, counts);
  if (got.dc != dc or got.shift != shift) { fail("adjustDC", i, debug_show got # " vs " # debug_show (dc, shift)) };
};

let keeps : [([Nat], Rules.Mode, ?{ #adv; #dis }, Nat)] = [
${keeps.map(c => `  ([${c.dice.join(', ')}], ${mode(c.mode)}, ${c.a ? '?#' + c.a : 'null'}, ${H.rollDamageLine ? '' : ''}${(() => { const dice = c.dice; return require(path.resolve(process.env.HEXDIE || path.join(__dirname, '../../../hex-die'), 'engine/hexdie.js')) && (() => { const hi = Math.max(...dice), lo = Math.min(...dice); if (dice.length === 1 || !c.a) return dice[0]; return ((c.mode === 'over') === (c.a === 'adv')) ? hi : lo; })(); })()})`).join(',\n')}
];
for (i in keeps.keys()) {
  let (d, m, a, e) = keeps[i];
  let got = Rules.keepLine(d, m, a);
  if (got != e) { fail("keepLine", i, debug_show got # " vs " # debug_show e) };
};

assert failures == 0;
Debug.print("RulesParity ok: ${checks.length} checks, ${reveals.length} reveals, ${mitig.length} mitigations, ${adj.length} DC adjustments, ${keeps.length} line keeps");
`;
fs.writeFileSync(path.resolve(__dirname, '../../sentient-economic-backend/tests/RulesParity.mo'), o);
console.log('wrote', checks.length, reveals.length, mitig.length, adj.length, keeps.length, 'bytes', o.length);
