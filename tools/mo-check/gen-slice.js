// Generates sentient-economic-backend/tests/VerticalSlice.mo: the Move 7 demo, end to end, in the Motoko interpreter.
// identify-eweself's example Character (a real file the app produced) -> Character.validate -> register -> a quest carrying the Character's
// Personal DC -> Hex-Die check (on-chain dice from a fixed entropy blob) -> Grace-point line reveal -> one damage application ->
// settle rewards -> convert crystals to a claim -> withdrawal order -> custodian settlement. Every step prints, so DCs and balances visibly change.
// usage: IDENTIFY_EWESELF=../identify-eweself node gen-slice.js
const fs = require('fs'), path = require('path');
const dir = path.resolve(process.env.IDENTIFY_EWESELF || path.join(__dirname, '../../../identify-eweself'));
const base = JSON.parse(fs.readFileSync(path.join(dir, 'docs/example-character.json'), 'utf8'));
const { lit } = require('./character-lit');
const out = `// GENERATED by tools/mo-check/gen-slice.js. Do not hand-edit. Run: tools/mo-check/run-slice.sh
import Character "../src/Character";
import Rules "../src/Rules";
import Dice "../src/Dice";
import Data "../src/Data";
import Sentient "../src/Sentient";
import Progression "../src/Progression";
import Bank "../src/Bank";
import Random "mo:base/Random";
import Blob "mo:base/Blob";
import Array "mo:base/Array";
import Nat8 "mo:base/Nat8";
import Nat32 "mo:base/Nat32";
import Nat "mo:base/Nat";
import Int "mo:base/Int";
import Principal "mo:base/Principal";
import Debug "mo:base/Debug";

func say(s : Text) { Debug.print(s) };
func ok<T>(r : { #ok : T; #err : Text }, what : Text) : T { switch (r) { case (#ok v) v; case (#err e) { Debug.print("SLICE FAILED at " # what # ": " # e); assert false; loop {} } } };

// 1. The Character the creation app produced
let c : Character.Character = ${lit(base)};
let problems = Character.validate(c);
say("1. Character " # c.name # " validates: " # (if (problems.size() == 0) "yes" else "NO"));
assert problems.size() == 0;

// 2. Register a Sentient (starting Fate Points 3: the table convention; the Hub takes the number as an argument)
var s = Sentient.newState(3);
say("2. Registered. FP " # Nat.toText(s.fate.fp));

// 3. A quest carrying a DC: the Character's physical Personal DC, in its band's mode
let baseDc = c.dc.physical.value;
let mode : Rules.Mode = if (c.dc.physical.mode == #over) #over else #under;
say("3. Physical DC " # Nat.toText(baseDc) # " (" # (if (mode == #over) "roll-over" else "roll-under") # ")");

// 4. A Hex-Die resolution on dice from a fixed entropy blob (the canister uses raw_rand; same code path)
func blobFor(seed : Nat) : Blob {
  var x : Nat32 = Nat32.fromNat(seed);
  Blob.fromArray(Array.tabulate<Nat8>(32, func(_) { x := x *% 1664525 +% 1013904223; Nat8.fromNat(Nat32.toNat(x >> 24)) }));
};
func resolveWith(seed : Nat, dc : Nat) : (Rules.CheckResult, Dice.Rolls) {
  let rolls = switch (Dice.rolls(Random.Finite(blobFor(seed)), c.dieTier)) { case null { assert false; loop {} }; case (?r) r };
  let input : Rules.Input = { cast = rolls.cast; roll = rolls.roll; die = c.dieTier; mod = 0; dc; modeDc = ?baseDc; stepDown = false; pullRoll = rolls.pull; resistPull = false };
  (ok(Rules.resolveCheck(input), "resolveCheck"), rolls);
};
// first seed whose scene a line reveal improves into a PASS, so the demo shows the reveal and pays rewards
var seed = 1;
var found = false;
while (not found and seed < 5000) {
  let (r, rolls) = resolveWith(seed, baseDc);
  switch (Rules.revealLine(r, rolls.line)) { case (#ok (r2, true)) { if (r2.pass) { found := true } else { seed += 1 } }; case _ { seed += 1 } };
};
assert found;
let (r0, rolls) = resolveWith(seed, baseDc);
say("4. Cast " # Nat.toText(r0.cast) # " die d" # Nat.toText(r0.die) # " roll " # Nat.toText(r0.roll) # " -> " # r0.joinName # " (" # (if (r0.pass) "pass" else "fail") # ", tier " # (switch (r0.tier) { case (#T) "T"; case (#C) "C"; case (#D) "D" }) # ")");

// 5. Grace-point line reveal: line d6 = rolls.line
let (r1, revealed) = ok(Rules.revealLine(r0, rolls.line), "revealLine");
say("5. Line reveal (" # Nat.toText(rolls.line) # ") applied: " # (if revealed "yes" else "no") # " -> " # r1.joinName);
assert revealed;

// 6. One damage application: a level-6 damage line shifts the DC by 1 (over rises, under falls); the mode never changes
let adj = Rules.adjustDC(baseDc, mode, [0, 0, 0, 0, 0, 1]);
say("6. Damage line L6: DC " # Nat.toText(baseDc) # " -> " # Nat.toText(adj.dc));
assert adj.shift == 1 and adj.dc != baseDc;

// 7. Settle the scene: rewards for the final join cell into the Sentient
let prize = Data.questTemplates[r1.cast - 1].rewards;
let before = s;
let (s1, rewards) = Sentient.settle(s, r1, prize);
s := s1;
say("7. Rewards granted: " # Nat.toText(rewards.size()) # " item(s). FP " # Nat.toText(before.fate.fp) # " -> " # Nat.toText(s.fate.fp) # ", Grace " # Nat.toText(before.moral.grace) # " -> " # Nat.toText(s.moral.grace) # ", Skulduggery " # Nat.toText(before.moral.skulduggery) # " -> " # Nat.toText(s.moral.skulduggery) # ", Type1 " # Nat.toText(s.balance.type1) # ", Type2 " # Nat.toText(s.balance.type2) # ", Type4 " # Nat.toText(s.balance.type4));
assert s.checks == 1;

// 8. Spend two Fate Points: 1 Skulduggery; then convert everything convertible to a FUDDY claim
let (s2, owed) = ok(Sentient.spendFate(s, 2), "spendFate");
s := s2;
say("8. Spent 2 FP -> Skulduggery +" # Nat.toText(owed) # " (now " # Nat.toText(s.moral.skulduggery) # ")");
assert owed == 1;
let spend : Bank.Spend = { type1 = s.balance.type1; type2 = s.balance.type2; type3 = s.balance.type3; type4 = s.balance.type4; inGameFuddy = s.balance.inGameFuddy };
var acct = Bank.newAccount();
let (s3, a1, claimed) = ok(Bank.convert(Bank.defaultConfig, s, acct, spend), "convert");
s := s3; acct := a1;
say("9. Converted crystals + in-game FUDDY -> claim " # Nat.toText(claimed) # " (PLACEHOLDER rates; crystals now " # Nat.toText(s.balance.type1 + s.balance.type2 + s.balance.type3 + s.balance.type4) # ")");

// 9. Withdrawal order for the custodian, with the ledger fee out of the gross (fee 1 here is a stand-in: the real fee is UNVERIFIED until read)
let fee : Bank.Fee = { transfer = 1 };
let q = ok(Bank.quoteWithdrawal(Bank.defaultConfig, fee, claimed), "quote");
acct := ok(Bank.requestWithdrawal(acct, q), "request");
let order : Bank.Order = { id = 1; owner = Principal.fromText("2vxsx-fae"); gross = q.gross; fee = q.fee; net = q.net; created = 0; status = #Pending };
say("10. Order: gross " # Nat.toText(q.gross) # ", fee " # Nat.toText(q.fee) # ", net " # Nat.toText(q.net) # " (pending, claim " # Nat.toText(acct.claim) # ")");
let (acct2, order2) = ok(Bank.settleOrder(acct, order, #Settled "custodian-txid-placeholder"), "settle");
say("11. Custodian recorded settlement. Claim " # Nat.toText(acct2.claim) # ", settled gross " # Nat.toText(acct2.settledGross) # ", books balanced: " # (if (Bank.balanced(acct2)) "yes" else "NO"));
assert Bank.balanced(acct2) and order2.status == #Settled "custodian-txid-placeholder";
let st = Sentient.standing(s);
say("SLICE OK. Standing: villainy " # st.villainy # ", venerable " # st.venerableLevel # ", vices " # Nat.toText(st.vices) # ", virtues " # Nat.toText(st.virtues));
`;
fs.writeFileSync(path.resolve(__dirname, '../../sentient-economic-backend/tests/VerticalSlice.mo'), out);
console.log('wrote VerticalSlice.mo');
